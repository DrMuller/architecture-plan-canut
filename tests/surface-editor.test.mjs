assert.throws(()=>rememberColour([],'red'));
const materials=Array.from({length:6},(_,i)=>{const m=new THREE.MeshBasicMaterial();m.userData.surfaceKey='face-'+i;return m;});
const wall=new THREE.Mesh(new THREE.BoxGeometry(2,3,.07),materials);
const geometry=selectionGeometry(wall,new Set(['face-4']));
assert.equal(geometry.groups.length,1);assert.equal(geometry.groups[0].start,wall.geometry.groups[4].start);assert.equal(geometry.groups[0].count,6);assert.equal(geometry.groups[0].materialIndex,0);
assert.equal(wall.geometry.groups.length,6,'overlay does not mutate the original wall');
assert.equal(selectionGeometry(wall,new Set(['none'])),null);
const floor=new THREE.Mesh(new THREE.PlaneGeometry(2,2),materials[0]);
assert.equal(selectionGeometry(floor,new Set(['face-0'])).groups[0].count,6);
const overlay=new THREE.Mesh(geometry,[new THREE.MeshBasicMaterial()]);wall.add(overlay);wall.scale.y=.2;wall.position.y=.3;wall.updateMatrixWorld(true);assert.deepEqual(overlay.matrixWorld.elements,wall.matrixWorld.elements,'selection follows wall cuts');
const spec={surfaces:['wall'],finishes:['paint'],furnitureIds:[]};
const design={format:'ivry-design',version:1,units:'metres',materials:{wall:{finish:'paint',tint:'#445566',roughness:.65,scale:1}},textures:{},furniture:[],ceilings:{box:2.9,main:4},recentColours:colours};
